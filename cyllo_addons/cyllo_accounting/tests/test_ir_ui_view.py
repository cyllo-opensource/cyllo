from odoo.tests.common import TransactionCase

class TestIrUiView(TransactionCase):

    def test_type_selection(self):
        """Test if reconcile is in type selection."""
        view_model = self.env['ir.ui.view']
        types = dict(view_model._fields['type'].selection)
        self.assertIn('reconcile', types)
