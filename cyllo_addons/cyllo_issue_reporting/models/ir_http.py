from odoo import models

class IrHttp(models.AbstractModel):
    _inherit = 'ir.http'

    def session_info(self):
        res = super(IrHttp, self).session_info()
        res['is_issue_reporting'] = bool(
            self.env['ir.config_parameter'].sudo().get_param('cyllo_issue_reporting.is_issue_reporting')
        )
        return res
